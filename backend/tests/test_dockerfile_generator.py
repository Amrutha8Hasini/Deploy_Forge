"""Tests for Dockerfile generation (Module 4)."""

import json

import pytest

from app.services.detector import detect_project
from app.services.dockerfile_generator import GENERATED_DOCKERFILE_NAME, generate_dockerfile, write_dockerfile


def make_flask_project(folder):
    (folder / "requirements.txt").write_text("flask\ngunicorn\n")
    (folder / "app.py").write_text("app = None")


def test_python_dockerfile_contents(tmp_path):
    make_flask_project(tmp_path)
    dockerfile = generate_dockerfile(detect_project(tmp_path))
    assert dockerfile.startswith("# Generated by DeployForge")
    assert "FROM python:3.12-slim" in dockerfile
    assert "RUN pip install --no-cache-dir -r requirements.txt" in dockerfile
    assert "COPY . ." in dockerfile
    assert "EXPOSE 8000" in dockerfile
    assert "USER appuser" in dockerfile  # does not run as root
    assert 'CMD ["gunicorn", "--bind", "0.0.0.0:8000", "--workers", "2", "app:app"]' in dockerfile


def test_node_dockerfile_contents(tmp_path):
    (tmp_path / "package.json").write_text(json.dumps({"scripts": {"start": "node index.js"}}))
    dockerfile = generate_dockerfile(detect_project(tmp_path))
    assert "FROM node:20-alpine" in dockerfile
    assert "COPY package*.json ./" in dockerfile
    assert "RUN npm install --omit=dev" in dockerfile
    assert "EXPOSE 3000" in dockerfile
    assert 'CMD ["npm", "start"]' in dockerfile


def test_node_with_build_script_runs_build(tmp_path):
    (tmp_path / "package.json").write_text(json.dumps({"scripts": {"start": "node dist/index.js", "build": "tsc"}}))
    dockerfile = generate_dockerfile(detect_project(tmp_path))
    assert "RUN NODE_ENV=development npm install" in dockerfile
    assert "RUN npm run build" in dockerfile


def test_unsupported_project_raises(tmp_path):
    (tmp_path / "pom.xml").write_text("<project/>")
    with pytest.raises(ValueError):
        generate_dockerfile(detect_project(tmp_path))


def test_write_dockerfile_keeps_existing_dockerfile(tmp_path):
    make_flask_project(tmp_path)
    (tmp_path / "Dockerfile").write_text("FROM scratch\n")
    path = write_dockerfile(tmp_path, "FROM python:3.12-slim\n")
    assert path.name == GENERATED_DOCKERFILE_NAME
    assert (tmp_path / "Dockerfile").read_text() == "FROM scratch\n"  # untouched
    assert (tmp_path / ".dockerignore").is_file()
