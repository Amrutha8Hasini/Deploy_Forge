"""
Dockerfile generation.

Based on the detection result we fill in a small, readable Dockerfile
template. The file is saved as `Dockerfile.deployforge` inside the cloned repo,
so we never overwrite a Dockerfile the repository already has.
"""

import json
from pathlib import Path

from app.services.detector import DetectionResult

GENERATED_DOCKERFILE_NAME = "Dockerfile.deployforge"

# Files that should not be sent to Docker while building
DOCKERIGNORE_CONTENT = """.git
node_modules
__pycache__
*.pyc
.venv
venv
.env
"""

PYTHON_TEMPLATE = """# Generated by DeployForge for a {framework} application
FROM python:3.12-slim

# Do not create .pyc files and show logs immediately
ENV PYTHONDONTWRITEBYTECODE=1 \\
    PYTHONUNBUFFERED=1 \\
    PORT={port}

WORKDIR /app

# 1. Install dependencies first (this layer is cached between builds)
COPY requirements.txt .
RUN {install_command}

# 2. Copy the application files
COPY . .

# 3. Run as a normal user instead of root (basic security)
RUN useradd --create-home appuser && chown -R appuser /app
USER appuser

# 4. Expose the port and start the application
EXPOSE {port}
CMD {start_command}
"""

NODE_TEMPLATE = """# Generated by DeployForge for a {framework} application
FROM node:20-alpine

ENV NODE_ENV=production \\
    PORT={port}

WORKDIR /app

# 1. Install dependencies first (this layer is cached between builds)
COPY package*.json ./
RUN {install_command}

# 2. Copy the application files
COPY . .
{build_step}
# 3. Run as the non-root "node" user that comes with the image
RUN chown -R node:node /app
USER node

# 4. Expose the port and start the application
EXPOSE {port}
CMD {start_command}
"""


def generate_dockerfile(detection: DetectionResult) -> str:
    """Return the Dockerfile text for a supported project."""
    if not detection.supported:
        raise ValueError(f"Cannot generate a Dockerfile: {detection.message}")

    # JSON array form of CMD, e.g. ["python", "app.py"]
    start_command = json.dumps(detection.start_command)

    if detection.project_type == "python":
        return PYTHON_TEMPLATE.format(
            framework=detection.framework,
            port=detection.internal_port,
            install_command=detection.install_command,
            start_command=start_command,
        )

    if detection.project_type == "node":
        # When the project has a build script, we need dev dependencies for the
        # build, so NODE_ENV is only applied after installing.
        install = detection.install_command
        if detection.build_command:
            install = f"NODE_ENV=development {install}"
        build_step = f"RUN {detection.build_command}\n" if detection.build_command else ""
        return NODE_TEMPLATE.format(
            framework=detection.framework,
            port=detection.internal_port,
            install_command=install,
            build_step=build_step,
            start_command=start_command,
        )

    raise ValueError(f"Unsupported project type: {detection.project_type}")


def write_dockerfile(folder: Path, dockerfile_text: str) -> Path:
    """Save the generated Dockerfile (and a .dockerignore if missing)."""
    path = folder / GENERATED_DOCKERFILE_NAME
    path.write_text(dockerfile_text, encoding="utf-8")
    dockerignore = folder / ".dockerignore"
    if not dockerignore.exists():
        dockerignore.write_text(DOCKERIGNORE_CONTENT, encoding="utf-8")
    return path
