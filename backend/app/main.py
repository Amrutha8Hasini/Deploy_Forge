"""
DeployForge backend entry point.

Run locally with:   uvicorn app.main:app --reload --port 8000
API documentation:  http://localhost:8000/docs  (generated by FastAPI)
"""

from contextlib import asynccontextmanager

from fastapi import FastAPI
from fastapi.middleware.cors import CORSMiddleware

from app import config
from app.database import init_db
from app.routers import applications, auth, containers, deployments, monitoring
from app.services.deployment_service import mark_interrupted_deployments


@asynccontextmanager
async def lifespan(_app: FastAPI):
    # Runs once when the server starts
    init_db()
    mark_interrupted_deployments()
    yield


app = FastAPI(
    title="DeployForge API",
    description="A mini Platform as a Service: GitHub -> Docker image -> running container",
    version="1.0.0",
    lifespan=lifespan,
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=config.CORS_ORIGINS,
    allow_credentials=True,
    allow_methods=["*"],
    allow_headers=["*"],
)

app.include_router(auth.router)
app.include_router(applications.router)
app.include_router(deployments.router)
app.include_router(containers.router)
app.include_router(monitoring.router)


@app.get("/api/health", tags=["Health"])
def health():
    """Used by Docker Compose and the CI pipeline to check the backend is up."""
    return {"status": "ok", "service": "deployforge-backend"}
